package br.com.wdc.store.scripts.codegen;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;

/**
 * Generates the design tokens' code for every view technology from {@code br.com.wdc.store.design/src/main/tokens/tokens.json}
 * (W3C Design Tokens format): the palette, the spacing, the radii and the type.
 *
 * <p>
 * It writes {@code StoreTokens} (Java 8 syntax: SWT, the landing page) and its copy for Codename One;
 * {@code _tokens.scss} (Sass variables and a mixin of CSS custom properties) for the React shell, the TeaVM views and
 * Codename One's theme; {@code store_tokens.dart} for Flutter; {@code tokens.css} for Vaadin. The generated files are
 * committed; {@code DesignTokensTest} fails while they don't match the JSON.
 * </p>
 *
 * <pre>
 * mvn exec:java -pl br.com.wdc.store/br.com.wdc.store.scripts \
 *     -Dexec.mainClass="br.com.wdc.store.scripts.codegen.GenerateDesignTokens"
 * </pre>
 */
public final class GenerateDesignTokens {

    public static final Path SOURCE = Path.of("br.com.wdc.store/br.com.wdc.store.design/src/main/tokens/tokens.json");

    static final Path JAVA = Path.of("br.com.wdc.store/br.com.wdc.store.design/src/main/java/br/com/wdc/store/design"
            + "/StoreTokens.java");
    static final Path CN1_JAVA = Path.of("br.com.wdc.store/br.com.wdc.store.view.remote/remote.shell.cn1/common/src/main/java"
            + "/br/com/wdc/store/view/remote/shell/cn1/theme/StoreTokens.java");
    static final List<Path> SCSS = List.of(
            Path.of("br.com.wdc.store/br.com.wdc.store.view.remote/remote.shell.react/src/scss/generated/_tokens.scss"),
            Path.of("br.com.wdc.store/br.com.wdc.store.view.teavm/teavm.commons/src/main/scss/generated/_tokens.scss"),
            Path.of("br.com.wdc.store/br.com.wdc.store.view.remote/remote.shell.cn1/common/src/main/scss/generated/_tokens.scss"));
    static final Path DART = Path.of("br.com.wdc.store/br.com.wdc.store.view.remote/remote.shell.flutter/flutter.commons"
            + "/lib/src/generated/store_tokens.dart");
    static final Path CSS = Path.of("br.com.wdc.store/br.com.wdc.store.view.vaadin/src/main/resources/META-INF/resources"
            + "/styles/tokens.css");

    private static final String NOTICE = "Generated by GenerateDesignTokens from br.com.wdc.store.design/src/main/tokens/"
            + "tokens.json: do not edit, change the tokens and run it again.";

    /** One token, flattened: its group path ({@code color}, {@code font.size}), its name, type and value. */
    record Token(String group, String name, String type, String value, String description) {

        /** {@code color-primary-light}, {@code font-size-md}. */
        String kebab() {
            return (group + "." + name).replace('.', '-').replaceAll("([a-z0-9])([A-Z])", "$1-$2").toLowerCase();
        }

        /** {@code COLOR_PRIMARY_LIGHT}. */
        String constant() {
            return kebab().replace('-', '_').toUpperCase();
        }

        /** {@code primaryLight} for colors, {@code spaceMd}, {@code fontSizeMd}. */
        String camel() {
            var parts = (group.equals("color") ? name : group + "." + name).split("\\.");
            var sb = new StringBuilder(parts[0]);
            for (int i = 1; i < parts.length; i++) {
                sb.append(Character.toUpperCase(parts[i].charAt(0))).append(parts[i].substring(1));
            }
            return sb.toString();
        }

        /** The number of a dimension ({@code 16px} → 16). */
        int pixels() {
            return Integer.parseInt(value.replace("px", "").trim());
        }
    }

    private GenerateDesignTokens() {
    }

    public static void main(String[] args) {
        var fontes = Path.of(args.length > 0 ? args[0] : ".").toAbsolutePath().normalize();
        for (var file : render(fontes).entrySet()) {
            GenerateMessages.write(fontes.resolve(file.getKey()), file.getValue());
        }
    }

    /** Every generated file (path relative to {@code fontes/} → content), from the tokens under {@code fontes}. */
    public static Map<Path, String> render(Path fontes) {
        var tokens = read(fontes.resolve(SOURCE));
        var out = new LinkedHashMap<Path, String>();
        out.put(JAVA, java("br.com.wdc.store.design", tokens));
        out.put(CN1_JAVA, java("br.com.wdc.store.view.remote.shell.cn1.theme", tokens));
        var scss = scss(tokens);
        for (var path : SCSS) {
            out.put(path, scss);
        }
        out.put(DART, dart(tokens));
        out.put(CSS, "/* " + NOTICE + " */\n" + cssVariables(tokens));
        return out;
    }

    // :: Reading

    public static List<Token> read(Path file) {
        try {
            var root = JsonParser.parseString(Files.readString(file, StandardCharsets.UTF_8)).getAsJsonObject();
            var tokens = new ArrayList<Token>();
            flatten("", root, null, tokens);
            return tokens;
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

    private static void flatten(String path, JsonObject node, String inheritedType, List<Token> out) {
        var type = node.has("$type") ? node.get("$type").getAsString() : inheritedType;
        for (var entry : node.entrySet()) {
            var name = entry.getKey();
            if (name.startsWith("$") || !entry.getValue().isJsonObject()) {
                continue;
            }
            var child = entry.getValue().getAsJsonObject();
            if (child.has("$value")) {
                var childType = child.has("$type") ? child.get("$type").getAsString() : type;
                if (childType == null) {
                    throw new IllegalStateException("A token without a type: " + path + "." + name);
                }
                var description = child.has("$description") ? child.get("$description").getAsString() : null;
                out.add(new Token(path, name, childType, value(child.get("$value"), childType), description));
            } else {
                flatten(path.isEmpty() ? name : path + "." + name, child, type, out);
            }
        }
    }

    private static String value(JsonElement value, String type) {
        if (type.equals("fontFamily") && value.isJsonArray()) {
            var names = new ArrayList<String>();
            value.getAsJsonArray().forEach(e -> names.add(e.getAsString()));
            return String.join(", ", names);
        }
        var text = value.getAsString();
        if (type.equals("color") && !text.matches("#[0-9a-fA-F]{6}")) {
            throw new IllegalStateException("A color is #rrggbb: " + text);
        }
        if (type.equals("dimension") && !text.matches("\\d+px")) {
            throw new IllegalStateException("A dimension is whole pixels: " + text);
        }
        return type.equals("color") ? text.toLowerCase() : text;
    }

    // :: CSS

    /** {@code :root { --store-color-primary: #0d66d0; ... }}. */
    static String cssVariables(List<Token> tokens) {
        var sb = new StringBuilder(":root {\n");
        for (var token : tokens) {
            sb.append("  --store-").append(token.kebab()).append(": ").append(css(token)).append(";\n");
        }
        return sb.append("}\n").toString();
    }

    private static String css(Token token) {
        if (token.type().equals("fontFamily")) {
            var names = new ArrayList<String>();
            for (var name : token.value().split(",\\s*")) {
                names.add(name.contains(" ") ? "\"" + name + "\"" : name);
            }
            return String.join(", ", names);
        }
        return token.value();
    }

    private static String scss(List<Token> tokens) {
        var sb = new StringBuilder("// ").append(NOTICE).append("\n\n");
        for (var token : tokens) {
            if (token.description() != null) {
                sb.append("// ").append(token.description()).append("\n");
            }
            sb.append("$").append(token.kebab()).append(": ").append(css(token)).append(";\n");
        }
        sb.append("\n// The tokens as CSS custom properties (--store-...), for the web views: @include store-token-variables;\n");
        sb.append("@mixin store-token-variables {\n");
        for (var token : tokens) {
            sb.append("  --store-").append(token.kebab()).append(": #{$").append(token.kebab()).append("};\n");
        }
        return sb.append("}\n").toString();
    }

    // :: Java

    private static String java(String pkg, List<Token> tokens) {
        var sb = new StringBuilder("// @formatter:off\n// ").append(NOTICE).append("\npackage ").append(pkg).append(";\n\n");
        sb.append("/**\n * The WDC Store's design tokens: colors as {@code 0xRRGGBB} (and {@code _HEX}), spacing, radii and font\n");
        sb.append(" * sizes in pixels, font weights, the font family; {@link #CSS_VARIABLES}, the same as CSS custom properties.\n */\n");
        sb.append("public final class StoreTokens {\n\n    private StoreTokens() {\n    }\n\n");
        for (var token : tokens) {
            if (token.description() != null) {
                sb.append("    /** ").append(token.description()).append(" */\n");
            }
            switch (token.type()) {
            case "color" -> {
                sb.append("    public static final int ").append(token.constant()).append(" = 0x")
                        .append(token.value().substring(1)).append(";\n");
                sb.append("    public static final String ").append(token.constant()).append("_HEX = ")
                        .append(GenerateMessages.javaString(token.value())).append(";\n");
            }
            case "dimension" -> sb.append("    public static final int ").append(token.constant()).append(" = ")
                    .append(token.pixels()).append(";\n");
            case "fontWeight" -> sb.append("    public static final int ").append(token.constant()).append(" = ")
                    .append(token.value()).append(";\n");
            default -> sb.append("    public static final String ").append(token.constant()).append(" = ")
                    .append(GenerateMessages.javaString(token.value())).append(";\n");
            }
        }
        sb.append("\n    /** The tokens as CSS custom properties ({@code --store-color-primary}, ...), in a {@code :root} rule. */\n");
        sb.append("    public static final String CSS_VARIABLES = ");
        var lines = cssVariables(tokens).split("\n");
        for (int i = 0; i < lines.length; i++) {
            sb.append(i == 0 ? "" : "\n            + ").append(GenerateMessages.javaString(lines[i] + "\n"));
        }
        sb.append(";\n}\n");
        return sb.toString();
    }

    // :: Dart

    private static String dart(List<Token> tokens) {
        var sb = new StringBuilder("// ").append(NOTICE).append("\n\nimport 'package:flutter/painting.dart';\n\n");
        sb.append("/// The WDC Store's design tokens: colors, spacing, radii and font sizes in logical pixels, weights, family.\n");
        sb.append("abstract final class StoreTokens {\n");
        for (var token : tokens) {
            if (token.description() != null) {
                sb.append("  /// ").append(token.description()).append("\n");
            }
            switch (token.type()) {
            case "color" -> sb.append("  static const Color ").append(token.camel()).append(" = Color(0xFF")
                    .append(token.value().substring(1).toUpperCase()).append(");\n");
            case "dimension" -> sb.append("  static const double ").append(token.camel()).append(" = ")
                    .append(token.pixels()).append(";\n");
            case "fontWeight" -> sb.append("  static const FontWeight ").append(token.camel()).append(" = FontWeight.w")
                    .append(token.value()).append(";\n");
            default -> {
                var names = new ArrayList<String>();
                for (var name : token.value().split(",\\s*")) {
                    names.add(GenerateMessages.dartString(name));
                }
                sb.append("  static const List<String> ").append(token.camel()).append(" = [")
                        .append(String.join(", ", names)).append("];\n");
            }
            }
        }
        return sb.append("}\n").toString();
    }
}
