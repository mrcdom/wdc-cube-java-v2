package br.com.wdc.store.scripts.codegen;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.TreeMap;
import java.util.regex.Pattern;
import java.util.stream.Stream;

import com.google.gson.JsonParser;

/**
 * Generates the UI text catalog's code for every view technology from {@code br.com.wdc.store.i18n/src/main/catalog}:
 * one folder per language ({@code en-US}, {@code pt-BR}), each with JSON files of key → text with
 * {@code {placeholders}}, merged in name order.
 *
 * <p>
 * It writes {@code StoreMessages} (the texts and their formatting, Java 8 syntax) and {@code Messages} (one factory per
 * key, a parameter per placeholder) in {@code br.com.wdc.store.i18n}; a copy of {@code StoreMessages} for Codename One;
 * {@code messages.ts} for the React shell; {@code messages.dart} for the Flutter shell. The generated files are
 * committed; {@code MessagesCatalogTest} fails while they don't match the catalog, a language misses a key, or a key's
 * placeholders differ between languages.
 * </p>
 *
 * <p>
 * Run from the {@code fontes/} directory:
 * </p>
 *
 * <pre>
 * mvn exec:java -pl br.com.wdc.store/br.com.wdc.store.scripts \
 *     -Dexec.mainClass="br.com.wdc.store.scripts.codegen.GenerateMessages"
 * </pre>
 */
public final class GenerateMessages {

    /** The default language, first: the repository's. */
    public static final List<String> LANGUAGES = List.of("en-US", "pt-BR");

    public static final Path CATALOG = Path.of("br.com.wdc.store/br.com.wdc.store.i18n/src/main/catalog");

    static final Path JAVA_DIR = Path.of("br.com.wdc.store/br.com.wdc.store.i18n/src/main/java/br/com/wdc/store/i18n");
    static final Path CN1_JAVA = Path.of("br.com.wdc.store/br.com.wdc.store.view.remote/remote.shell.cn1/common/src/main/java"
            + "/br/com/wdc/store/view/remote/shell/cn1/i18n/StoreMessages.java");
    static final Path TS = Path.of("br.com.wdc.store/br.com.wdc.store.view.remote/remote.shell.react/src/scripts/generated"
            + "/messages.ts");
    static final Path DART = Path.of("br.com.wdc.store/br.com.wdc.store.view.remote/remote.shell.flutter/flutter.commons"
            + "/lib/src/generated/messages.dart");

    private static final Pattern PLACEHOLDER = Pattern.compile("\\{([A-Za-z][A-Za-z0-9]*)}");

    private static final String NOTICE = "Generated by GenerateMessages from br.com.wdc.store.i18n/src/main/catalog: "
            + "do not edit, change the catalog and run it again.";

    private GenerateMessages() {
    }

    public static void main(String[] args) {
        var fontes = Path.of(args.length > 0 ? args[0] : ".").toAbsolutePath().normalize();
        for (var file : render(fontes).entrySet()) {
            write(fontes.resolve(file.getKey()), file.getValue());
        }
    }

    /** Every generated file (path relative to {@code fontes/} → content), from the catalog under {@code fontes}. */
    public static Map<Path, String> render(Path fontes) {
        var catalog = read(fontes.resolve(CATALOG));
        var out = new LinkedHashMap<Path, String>();
        out.put(JAVA_DIR.resolve("StoreMessages.java"), storeMessages("br.com.wdc.store.i18n", catalog));
        out.put(JAVA_DIR.resolve("Messages.java"), factories(catalog));
        out.put(CN1_JAVA, storeMessages("br.com.wdc.store.view.remote.shell.cn1.i18n", catalog));
        out.put(TS, typescript(catalog));
        out.put(DART, dart(catalog));
        return out;
    }

    // :: Catalog

    /** The texts of each language, in key order; checked to have the same keys and placeholders. */
    public static Map<String, Map<String, String>> read(Path dir) {
        var catalog = new LinkedHashMap<String, Map<String, String>>();
        for (var language : LANGUAGES) {
            var texts = new TreeMap<String, String>();
            var origin = new LinkedHashMap<String, String>();
            try (Stream<Path> files = Files.list(dir.resolve(language))) {
                for (var file : files.filter(p -> p.toString().endsWith(".json")).sorted().toList()) {
                    var json = JsonParser.parseString(Files.readString(file, StandardCharsets.UTF_8)).getAsJsonObject();
                    for (var entry : json.entrySet()) {
                        var previous = origin.put(entry.getKey(), file.getFileName().toString());
                        if (previous != null) {
                            throw new IllegalStateException(language + ": the key " + entry.getKey() + " is in "
                                    + previous + " and in " + file.getFileName());
                        }
                        texts.put(entry.getKey(), entry.getValue().getAsString());
                    }
                }
            } catch (IOException e) {
                throw new UncheckedIOException(e);
            }
            catalog.put(language, texts);
        }
        check(catalog);
        return catalog;
    }

    private static void check(Map<String, Map<String, String>> catalog) {
        var reference = catalog.get(LANGUAGES.get(0));
        for (var language : LANGUAGES.subList(1, LANGUAGES.size())) {
            var texts = catalog.get(language);
            var missing = new LinkedHashSet<>(reference.keySet());
            missing.removeAll(texts.keySet());
            var extra = new LinkedHashSet<>(texts.keySet());
            extra.removeAll(reference.keySet());
            if (!missing.isEmpty() || !extra.isEmpty()) {
                throw new IllegalStateException(language + ": missing keys " + missing + ", keys not in "
                        + LANGUAGES.get(0) + " " + extra);
            }
            for (var key : reference.keySet()) {
                if (!placeholders(reference.get(key)).equals(placeholders(texts.get(key)))) {
                    throw new IllegalStateException(language + ": the placeholders of " + key + " differ from "
                            + LANGUAGES.get(0) + "'s");
                }
            }
        }
        for (var key : reference.keySet()) {
            if (!key.matches("[a-z][A-Za-z0-9]*(\\.[a-z][A-Za-z0-9]*)*")) {
                throw new IllegalStateException("A key is dotted camelCase words: " + key);
            }
        }
    }

    /** The placeholders of a text, in order of first use. */
    public static Set<String> placeholders(String text) {
        var names = new LinkedHashSet<String>();
        var matcher = PLACEHOLDER.matcher(text);
        while (matcher.find()) {
            names.add(matcher.group(1));
        }
        return names;
    }

    // :: Java

    private static String storeMessages(String pkg, Map<String, Map<String, String>> catalog) {
        var sb = new StringBuilder();
        sb.append("// @formatter:off\n// ").append(NOTICE).append("\npackage ").append(pkg).append(";\n\n");
        sb.append("import java.util.HashMap;\nimport java.util.Map;\n\n");
        sb.append("/**\n * The UI texts of the WDC Store in each language, by key, and their formatting: {@code {name}} placeholders\n");
        sb.append(" * are replaced by the arguments of the same name. A language is chosen from a tag ({@code pt-BR}, {@code pt},\n");
        sb.append(" * {@code en}); a key a language lacks falls back to the default language's text, then to the key itself.\n */\n");
        sb.append("public final class StoreMessages {\n\n");
        sb.append("    /** The default language. */\n    public static final String DEFAULT_LANGUAGE = \"")
                .append(LANGUAGES.get(0)).append("\";\n\n");
        sb.append("    /** The languages of the catalog, the default first. */\n    public static final String[] LANGUAGES = { ");
        sb.append(String.join(", ", LANGUAGES.stream().map(GenerateMessages::javaString).toList())).append(" };\n\n");
        for (var key : catalog.get(LANGUAGES.get(0)).keySet()) {
            sb.append("    public static final String ").append(constant(key)).append(" = ").append(javaString(key))
                    .append(";\n");
        }
        sb.append("\n    private static final Map<String, Map<String, String>> TEXTS = new HashMap<String, Map<String, String>>();\n\n");
        sb.append("    static {\n");
        for (var language : LANGUAGES) {
            sb.append("        Map<String, String> ").append(variable(language)).append(" = new HashMap<String, String>();\n");
            for (var entry : catalog.get(language).entrySet()) {
                sb.append("        ").append(variable(language)).append(".put(").append(constant(entry.getKey()))
                        .append(", ").append(javaString(entry.getValue())).append(");\n");
            }
            sb.append("        TEXTS.put(").append(javaString(language)).append(", ").append(variable(language)).append(");\n");
        }
        sb.append("    }\n\n");
        sb.append("""
                    private StoreMessages() {
                    }

                    /** The catalog's language for a tag: the exact one, else the first with the same language, else the default. */
                    public static String language(String tag) {
                        if (tag == null || tag.isEmpty()) {
                            return DEFAULT_LANGUAGE;
                        }
                        String normalized = tag.replace('_', '-');
                        for (String language : LANGUAGES) {
                            if (language.equalsIgnoreCase(normalized)) {
                                return language;
                            }
                        }
                        int dash = normalized.indexOf('-');
                        String base = dash < 0 ? normalized : normalized.substring(0, dash);
                        for (String language : LANGUAGES) {
                            if (language.toLowerCase().startsWith(base.toLowerCase() + "-")) {
                                return language;
                            }
                        }
                        return DEFAULT_LANGUAGE;
                    }

                    /** The text of {@code key} in the language of {@code tag}, its placeholders as they are. */
                    public static String text(String tag, String key) {
                        String text = TEXTS.get(language(tag)).get(key);
                        if (text == null) {
                            text = TEXTS.get(DEFAULT_LANGUAGE).get(key);
                        }
                        return text != null ? text : key;
                    }

                    /** The text of {@code key} in the language of {@code tag}, each {@code {name}} replaced by its argument. */
                    public static String format(String tag, String key, Map<String, String> args) {
                        String text = text(tag, key);
                        if (args == null || args.isEmpty() || text.indexOf('{') < 0) {
                            return text;
                        }
                        StringBuilder out = new StringBuilder(text.length() + 16);
                        int i = 0;
                        while (i < text.length()) {
                            char c = text.charAt(i);
                            int close = c == '{' ? text.indexOf('}', i) : -1;
                            if (close > i) {
                                String name = text.substring(i + 1, close);
                                if (args.containsKey(name)) {
                                    out.append(args.get(name));
                                    i = close + 1;
                                    continue;
                                }
                            }
                            out.append(c);
                            i++;
                        }
                        return out.toString();
                    }
                }
                """);
        return sb.toString();
    }

    private static String factories(Map<String, Map<String, String>> catalog) {
        var reference = catalog.get(LANGUAGES.get(0));
        var sb = new StringBuilder();
        sb.append("// @formatter:off\n// ").append(NOTICE).append("\npackage br.com.wdc.store.i18n;\n\n");
        sb.append("/**\n * One {@link Message} per key of the catalog ({@link StoreMessages}), with a parameter per placeholder: a\n");
        sb.append(" * message that lacks an argument does not compile.\n */\n");
        sb.append("public final class Messages {\n\n    private Messages() {\n    }\n");
        for (var entry : reference.entrySet()) {
            var names = new ArrayList<>(placeholders(entry.getValue()));
            sb.append("\n    /** ").append(javadoc(entry.getValue())).append(" */\n");
            sb.append("    public static Message ").append(method(entry.getKey())).append("(");
            sb.append(String.join(", ", names.stream().map(n -> "Object " + n).toList())).append(") {\n");
            sb.append("        return Message.of(StoreMessages.").append(constant(entry.getKey()));
            for (var name : names) {
                sb.append(", ").append(javaString(name)).append(", ").append(name);
            }
            sb.append(");\n    }\n");
        }
        sb.append("}\n");
        return sb.toString();
    }

    // :: TypeScript

    private static String typescript(Map<String, Map<String, String>> catalog) {
        var sb = new StringBuilder();
        sb.append("// ").append(NOTICE).append("\n/* eslint-disable */\n\n");
        sb.append("/** The languages of the catalog, the default first. */\n");
        sb.append("export const LANGUAGES = [").append(String.join(", ", LANGUAGES.stream().map(GenerateMessages::jsString).toList()))
                .append("] as const\n\nexport type Language = (typeof LANGUAGES)[number]\n\n");
        sb.append("export const DEFAULT_LANGUAGE: Language = ").append(jsString(LANGUAGES.get(0))).append("\n\n");
        sb.append("export type MessageKey =\n");
        var keys = new ArrayList<>(catalog.get(LANGUAGES.get(0)).keySet());
        for (int i = 0; i < keys.size(); i++) {
            sb.append("  | ").append(jsString(keys.get(i))).append(i == keys.size() - 1 ? "\n\n" : "\n");
        }
        sb.append("/** A text to show, as it travels from the presentation: a key and the values of its placeholders. */\n");
        sb.append("export interface Message {\n  key: string\n  args?: Record<string, string>\n}\n\n");
        sb.append("const TEXTS: Record<Language, Record<MessageKey, string>> = {\n");
        for (var language : LANGUAGES) {
            sb.append("  ").append(jsString(language)).append(": {\n");
            for (var entry : catalog.get(language).entrySet()) {
                sb.append("    ").append(jsString(entry.getKey())).append(": ").append(jsString(entry.getValue())).append(",\n");
            }
            sb.append("  },\n");
        }
        sb.append("}\n\n");
        sb.append("""
                /** The catalog's language for a tag: the exact one, else the first with the same language, else the default. */
                export function languageOf(tag: string | null | undefined): Language {
                  if (!tag) return DEFAULT_LANGUAGE
                  const normalized = tag.replace("_", "-").toLowerCase()
                  const exact = LANGUAGES.find((l) => l.toLowerCase() === normalized)
                  if (exact) return exact
                  const base = normalized.split("-")[0]
                  return LANGUAGES.find((l) => l.toLowerCase().startsWith(base + "-")) ?? DEFAULT_LANGUAGE
                }

                /** The text of a key in a language, each {name} replaced by its argument. */
                export function text(language: Language, key: MessageKey | string, args?: Record<string, string>): string {
                  const texts = TEXTS[language] as Record<string, string>
                  const fallback = TEXTS[DEFAULT_LANGUAGE] as Record<string, string>
                  const raw = texts[key] ?? fallback[key] ?? key
                  if (!args) return raw
                  return raw.replace(/\\{([A-Za-z][A-Za-z0-9]*)\\}/g, (whole, name: string) => (name in args ? args[name] : whole))
                }

                /** The text of a message from the presentation, in a language. */
                export function translate(language: Language, message: Message | null | undefined): string {
                  return message ? text(language, message.key, message.args) : ""
                }
                """);
        return sb.toString();
    }

    // :: Dart

    private static String dart(Map<String, Map<String, String>> catalog) {
        var sb = new StringBuilder();
        sb.append("// ").append(NOTICE).append("\n// ignore_for_file: lines_longer_than_80_chars\n\n");
        sb.append("/// The languages of the catalog, the default first.\nconst List<String> languages = [")
                .append(String.join(", ", LANGUAGES.stream().map(GenerateMessages::dartString).toList())).append("];\n\n");
        sb.append("const String defaultLanguage = ").append(dartString(LANGUAGES.get(0))).append(";\n\n");
        sb.append("/// The keys of the catalog.\nabstract final class MessageKeys {\n");
        for (var key : catalog.get(LANGUAGES.get(0)).keySet()) {
            sb.append("  static const String ").append(method(key)).append(" = ").append(dartString(key)).append(";\n");
        }
        sb.append("}\n\nconst Map<String, Map<String, String>> _texts = {\n");
        for (var language : LANGUAGES) {
            sb.append("  ").append(dartString(language)).append(": {\n");
            for (var entry : catalog.get(language).entrySet()) {
                sb.append("    ").append(dartString(entry.getKey())).append(": ").append(dartString(entry.getValue())).append(",\n");
            }
            sb.append("  },\n");
        }
        sb.append("};\n\n");
        sb.append("""
                /// The catalog's language for a tag: the exact one, else the first with the same language, else the default.
                String languageOf(String? tag) {
                  if (tag == null || tag.isEmpty) return defaultLanguage;
                  final normalized = tag.replaceAll('_', '-').toLowerCase();
                  for (final l in languages) {
                    if (l.toLowerCase() == normalized) return l;
                  }
                  final base = normalized.split('-').first;
                  for (final l in languages) {
                    if (l.toLowerCase().startsWith('$base-')) return l;
                  }
                  return defaultLanguage;
                }

                final RegExp _placeholder = RegExp(r'\\{([A-Za-z][A-Za-z0-9]*)\\}');

                /// The text of a key in a language, each {name} replaced by its argument.
                String text(String language, String key, [Map<String, String>? args]) {
                  final raw = _texts[language]?[key] ?? _texts[defaultLanguage]?[key] ?? key;
                  if (args == null || args.isEmpty) return raw;
                  return raw.replaceAllMapped(_placeholder, (m) => args[m.group(1)!] ?? m.group(0)!);
                }

                /// The text of a message from the presentation (`{"key", "args"}` as it travels), in a language.
                String translate(String language, Object? message) {
                  if (message is! Map) return message is String ? message : '';
                  final key = message['key'];
                  if (key is! String) return '';
                  final rawArgs = message['args'];
                  final args = rawArgs is Map ? rawArgs.map((k, v) => MapEntry('$k', '$v')) : null;
                  return text(language, key, args);
                }
                """);
        return sb.toString();
    }

    // :: Helpers

    /** {@code error.signin.tooMany} → {@code ERROR_SIGNIN_TOO_MANY}. */
    static String constant(String key) {
        return key.replace('.', '_').replaceAll("([a-z0-9])([A-Z])", "$1_$2").toUpperCase();
    }

    /** {@code error.signin.tooMany} → {@code errorSigninTooMany}. */
    static String method(String key) {
        var parts = key.split("\\.");
        var sb = new StringBuilder(parts[0]);
        for (int i = 1; i < parts.length; i++) {
            sb.append(Character.toUpperCase(parts[i].charAt(0))).append(parts[i].substring(1));
        }
        return sb.toString();
    }

    private static String variable(String language) {
        return language.replace("-", "").toLowerCase();
    }

    static String javaString(String s) {
        var sb = new StringBuilder("\"");
        for (char c : s.toCharArray()) {
            switch (c) {
            case '"' -> sb.append("\\\"");
            case '\\' -> sb.append("\\\\");
            case '\n' -> sb.append("\\n");
            default -> {
                if (c < 0x20 || c > 0x7e) {
                    sb.append(String.format("\\u%04x", (int) c));
                } else {
                    sb.append(c);
                }
            }
            }
        }
        return sb.append('"').toString();
    }

    static String jsString(String s) {
        return "\"" + s.replace("\\", "\\\\").replace("\"", "\\\"").replace("\n", "\\n") + "\"";
    }

    static String dartString(String s) {
        return "'" + s.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$").replace("\n", "\\n") + "'";
    }

    private static String javadoc(String text) {
        return text.replace("*/", "*&#47;").replace("{", "&#123;").replace("}", "&#125;");
    }

    static void write(Path file, String content) {
        try {
            Files.createDirectories(file.getParent());
            Files.writeString(file, content, StandardCharsets.UTF_8);
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }
}
